import { test, expect } from '@playwright/test';
const token = process.env.DEV_AUTH_TOKEN;
test.skip(!token, 'DEV_AUTH_TOKEN required; use a synthetic-data development server');

test('register, search, reopen, correct, retain background and review duplicates', async ({ page }) => {
  const unique = Date.now().toString().slice(-8);
  const name = `Synthetic Sara ${unique}`;
  const phone = `+2010${unique}`;
  await page.goto('/');
  await page.getByLabel('Development access key').fill(token!);
  await page.getByRole('button', { name: 'Open registry' }).click();
  await expect(page.getByRole('heading', { name: 'Patients', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '+ Register patient', exact: true }).click();
  await page.getByLabel('English name').fill(name);
  await page.getByLabel('Arabic name').fill(`سارة طفلة تجريبية ${unique}`);
  await page.getByLabel('Date of birth', { exact: true }).fill('2024-05-01');
  await page.getByLabel('Sex for growth reference').selectOption('female');
  await page.getByLabel('Guardian full name').fill('Synthetic Mother');
  await page.getByLabel('Guardian phone').fill(phone);
  await page.getByLabel('Relationship').selectOption('mother');
  await page.getByRole('button', { name: 'Medical & birth background' }).click();
  await page.getByLabel('NICU admission').selectOption('unknown');
  await page.getByLabel('Birth weight (kg)').fill('2.8');
  await page.getByRole('button', { name: 'Register patient', exact: true }).click();
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  await expect(page.getByText('Allergy review: unknown')).toBeVisible();
  await expect(page.getByText('Form background v2', { exact: false })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Add background', exact: true })).toBeEnabled();
  await page.screenshot({ path: 'docs/screenshots/unit-01-overview.png', fullPage: true });
  await page.getByRole('button', { name: 'Correct details' }).click();
  await page.getByLabel('English name').fill(`${name} Corrected`);
  await page.getByLabel('Correction reason').fill('Corrected synthetic spelling after guardian review');
  await page.getByRole('button', { name: 'Save correction' }).click();
  await expect(page.getByRole('heading', { name: `${name} Corrected`, exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add background' }).click();
  await page.getByLabel('Neonatal ventilation').selectOption('no');
  await page.getByRole('button', { name: 'Save background', exact: true }).click();
  await expect(page.getByText('Form background v2', { exact: false })).toHaveCount(2);
  await page.getByRole('tab', { name: 'Growth', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Growth will be built in a later unit' })).toBeVisible();
  await page.getByRole('button', { name: 'All patients' }).click();
  await page.getByRole('textbox', { name: 'Search patients' }).fill(unique);
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(page.getByRole('button', { name: `${name} Corrected`, exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: 'Search patients' }).fill(`سارة طفلة تجريبية ${unique}`);
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(page.getByRole('button', { name: `${name} Corrected`, exact: true })).toBeVisible();
  await page.screenshot({ path: 'docs/screenshots/unit-01-registry.png', fullPage: true });
  await page.getByRole('button', { name: `${name} Corrected`, exact: true }).click();
  await expect(page.getByText('Form background v2', { exact: false })).toHaveCount(2);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'docs/screenshots/unit-01-mobile.png', fullPage: true });
  await expect(page.getByRole('button', { name: 'Correct details' })).toBeVisible();
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole('button', { name: 'All patients' }).click();
  await page.getByRole('button', { name: '+ Register patient', exact: true }).click();
  await page.getByLabel('English name').fill(`${name} Corrected`);
  await page.getByLabel('Date of birth', { exact: true }).fill('2024-05-01');
  await page.getByLabel('Guardian full name').fill('Synthetic Mother');
  await page.getByLabel('Guardian phone').fill(phone);
  await page.getByRole('button', { name: 'Register patient', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Possible existing records' })).toBeVisible();
  await page.getByRole('button', { name: 'Open record', exact: true }).click();
  await expect(page.getByRole('heading', { name: `${name} Corrected`, exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Open the clinic registry' })).toBeVisible();
  await page.getByLabel('Development access key').fill(token!);
  await page.getByRole('button', { name: 'Open registry' }).click();
  await page.getByRole('textbox', { name: 'Search patients' }).fill(phone);
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(page.getByRole('button', { name: `${name} Corrected`, exact: true })).toBeVisible();
});
