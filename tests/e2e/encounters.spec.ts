import { test, expect } from '@playwright/test';
const token = process.env.DEV_AUTH_TOKEN;
test.skip(!token, 'Synthetic development credentials required');
test('dated visit, measurements, review, signature, immutable note and signed correction', async ({ page, request }) => {
  const suffix = Date.now().toString().slice(-8);
  const name = `Synthetic Visit ${suffix}`;
  const created = await request.post('/api/v1/patients', { headers: {Authorization:`Bearer ${token}`, 'Idempotency-Key':crypto.randomUUID()},
    data:{name_en:name,dob:'2024-01-01',guardian:{name:'Synthetic Guardian',phone_e164:`+2011${suffix}`,relation:'father'}} });
  expect(created.status()).toBe(201);
  await page.goto('/');
  await page.getByLabel('Development access key').fill(token!);
  await page.getByRole('button',{name:'Open registry'}).click();
  await page.getByLabel('Search patients').fill(name);
  await page.getByRole('button',{name:'Search',exact:true}).click();
  await page.getByRole('button',{name,exact:true}).click();
  await page.getByRole('tab',{name:'Encounters',exact:true}).click();
  await page.getByRole('button',{name:'Start visit',exact:true}).click();
  await page.getByLabel('Visit date and time').fill('2025-05-01T10:00');
  await page.getByLabel('Visit reason',{exact:true}).fill('Synthetic follow-up visit');
  await page.getByLabel('Consent context',{exact:true}).fill('Synthetic guardian present; context recorded');
  await expect(page.getByRole('tab',{name:'Overview',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Create draft visit'}).click();
  for (const label of ['History','Examination','Assessment','Plan']) await page.getByLabel(label,{exact:true}).fill(`Synthetic ${label.toLowerCase()}`);
  await page.getByLabel('Allergy review',{exact:true}).selectOption('reviewed');
  await page.getByLabel('Medication review',{exact:true}).selectOption('reviewed');
  await page.getByRole('button',{name:'Add measurement',exact:true}).click();
  await page.getByLabel('Weight (kg)',{exact:true}).fill('12.3');
  await page.getByLabel('Length / height (cm)').fill('85');
  await page.getByLabel('Position',{exact:true}).selectOption('standing');
  await page.getByLabel('Technique',{exact:true}).fill('Synthetic direct observation');
  await page.getByLabel('Equipment / reported device').fill('Synthetic scale and stadiometer');
  await page.getByLabel('Reason for save or status change').fill('Synthetic clinician documentation');
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  await expect(page.getByRole('button',{name:'Save draft',exact:true})).toBeDisabled();
  await page.getByLabel('Reason for save or status change').fill('Synthetic review complete');
  await page.getByRole('button',{name:'Submit for review',exact:true}).click();
  await expect(page.getByRole('textbox',{name:'History',exact:true})).toBeDisabled();
  await page.getByLabel('Reason for save or status change').fill('Synthetic clinician signing');
  await page.getByRole('button',{name:'Sign encounter',exact:true}).click();
  await expect(page.getByText('This snapshot is immutable.',{exact:false})).toBeVisible();
  await page.getByLabel('Correction reason',{exact:true}).fill('Clarify synthetic follow-up');
  await page.getByLabel('Addendum text').fill('Synthetic clarification retained with original note.');
  await page.getByRole('button',{name:'Sign addendum',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Signed addendum',exact:true})).toHaveCount(1);
  await expect(page.getByRole('textbox',{name:'History',exact:true})).toHaveValue('Synthetic history');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({path:'docs/screenshots/unit-02-encounter.png',fullPage:true});
  await page.getByRole('tab',{name:'Overview',exact:true}).click();
  await page.getByRole('tab',{name:'Encounters',exact:true}).click();
  await page.getByRole('button',{name:/Synthetic follow-up visit/}).click();
  await expect(page.getByRole('heading',{name:'Signed addendum',exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'docs/screenshots/unit-02-mobile.png',fullPage:true});
  await expect(page.getByLabel('Weight (kg)',{exact:true})).toHaveValue('12.3');
});
